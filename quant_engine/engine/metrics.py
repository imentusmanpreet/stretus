# ── Threshold helpers ──────────────────────────────────────────────────────────

def _get_thresholds(objective: str) -> dict:
    return PASS_FAIL_THRESHOLDS.get(
        str(objective).lower(),
        PASS_FAIL_THRESHOLDS["positional"],
    )


# ── Timestamp helpers ──────────────────────────────────────────────────────────

def _parse_timestamp(value: str) -> pd.Timestamp:
    timestamp = pd.to_datetime(value, utc=True)
    if getattr(timestamp, "tzinfo", None) is not None:
        return timestamp.tz_convert("UTC").tz_localize(None)
    return timestamp.tz_localize(None)


def _round(value: float, ndigits: int = 4) -> float:
    return round(float(value), ndigits)


def _format_trade_timestamp(value: str) -> str:
    return pd.to_datetime(value, utc=True).isoformat().replace("+00:00", "Z")


def _calendar_days(start_utc: str, end_utc: str) -> int:
    start = _parse_timestamp(start_utc).normalize()
    end   = _parse_timestamp(end_utc).normalize()
    return int((end - start).days) + 1


